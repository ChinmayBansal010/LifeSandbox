# ─── Audio Sample Factory & Inspector Unit Tests ────────────────────────────


def test_audio_factory_generates_valid_wav():
    """Verify that synthetic WAV has valid RIFF headers and audio metadata."""
    wav_bytes = AudioSampleFactory.create_wav(
        duration_seconds=0.5,
        sample_rate=16000,
        frequency_hz=440.0,
    )
    assert len(wav_bytes) > 44
    assert wav_bytes.startswith(b"RIFF")
    assert wav_bytes[8:12] == b"WAVE"

    meta = WavAudioInspector.inspect(wav_bytes)
    assert meta.is_valid is True
    assert meta.channels == 1
    assert meta.sample_rate == 16000
    assert meta.bits_per_sample == 16
    assert 0.49 <= meta.duration_seconds <= 0.51


def test_audio_factory_generates_standard_containers():
    """Verify WebM, MP3, and Ogg magic headers generated by AudioSampleFactory."""
    webm = AudioSampleFactory.create_webm(128)
    assert webm.startswith(b"\x1a\x45\xdf\xa3")

    mp3 = AudioSampleFactory.create_mp3(128)
    assert mp3.startswith(b"ID3")

    ogg = AudioSampleFactory.create_ogg(128)
    assert ogg.startswith(b"OggS")


def test_wav_inspector_detects_corrupt_audio():
    """Verify WavAudioInspector correctly flags non-WAV / corrupt streams."""
    corrupt = AudioSampleFactory.create_corrupt()
    meta = WavAudioInspector.inspect(corrupt)
    assert meta.is_valid is False
    assert meta.duration_seconds == 0.0


# ─── Speech Metrics Unit Tests (WER / CER) ──────────────────────────────────


def test_metrics_evaluator_exact_match():
    """Exact transcription match must produce 0.0 WER and 0.0 CER."""
    ref = "Life Sandbox helps weigh multi-criteria decisions."
    hyp = "Life Sandbox helps weigh multi-criteria decisions."
    metrics = SpeechMetricsEvaluator.evaluate(ref, hyp)
    assert metrics["wer"] == 0.0
    assert metrics["cer"] == 0.0
    assert metrics["exact_match"] is True
    assert metrics["accuracy"] == 1.0


def test_metrics_evaluator_with_errors():
    """Verify Levenshtein calculation for substitutions and deletions."""
    ref = "the quick brown fox"
    hyp = "the fast brown fox"
    # 1 word substituted out of 4 words -> WER = 0.25
    assert SpeechMetricsEvaluator.compute_wer(ref, hyp) == 0.25
    assert SpeechMetricsEvaluator.compute_cer(ref, hyp) > 0.0


def test_metrics_evaluator_normalization():
    """Verify case and punctuation normalization in evaluation."""
    ref = "Hello, World! Here is $100."
    hyp = "hello world here is 100"
    assert SpeechMetricsEvaluator.compute_wer(ref, hyp) == 0.0


