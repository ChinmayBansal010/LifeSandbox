    settings = get_settings()
    monkeypatch.setattr(settings, "tts_provider", "kokoro")

    mock_pipeline = MockKokoroPipeline(sample_rate=24000)

    with mock_speech_environment(kokoro_pipeline=mock_pipeline):
        with patch("app.main._kokoro_pipeline", return_value=mock_pipeline):
            with TestClient(app) as client:
                response = client.post(
                    "/api/v1/audio/speech",
                    json={
                        "text": "### Overview\nLife Sandbox models trade-offs with **confidence**.",
                        "voice": "af_bella",
                    },
                )

    assert response.status_code == 200
    assert response.headers["content-type"] == "audio/wav"

    # Verify WAV binary structure via harness inspector
    meta = WavAudioInspector.inspect(response.content)
    assert meta.is_valid is True
    assert meta.sample_rate == 24000
    assert meta.duration_seconds > 0.0

    # Verify voice and text passed to mock pipeline
    assert len(mock_pipeline.calls) == 1
    call = mock_pipeline.calls[0]
    assert call["voice"] == "af_bella"
    # Ensure markdown was cleaned
    assert "###" not in call["text"]
    assert "**" not in call["text"]
    assert "Life Sandbox models trade-offs with confidence." in call["text"]


